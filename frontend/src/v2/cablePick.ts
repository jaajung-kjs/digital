import type { V2Port } from './types';

/**
 * 「이 자산에서 포트 하나를 골라 달라」는 요청 — 평면도의 케이블 도구가 상세 패널에 보낸다.
 *
 * **왜 요청을 넘기는가**: 예전에는 평면도가 제 안에 포트 피커 패널을 하나 더 그렸다. 그래서
 * 상세 패널이 이미 열려 있으면 384px 패널이 둘 나란히 서서 도면이 그만큼 좁아졌고, 같은
 * 판(`PortFaceplate`)을 두 벌 그리는 코드도 둘이었다.
 *
 * 고르는 판은 이미 상세 패널의 「포트」 탭에 있다 — 거기가 「어느 포트가 비었나」를 보여 주는
 * 자리다. 그러니 판을 새로 그리는 대신 **그 탭을 고르는 모드로 돌린다**. 평면도는 무엇을
 * 골라야 하는지만 말하고, 고른 결과를 콜백으로 받는다.
 *
 * 상태 기계(어느 끝점까지 정해졌나)는 여전히 평면도가 갖는다 — 케이블은 도면의 일이다.
 */
export interface CablePickRequest {
  /** 포트를 고를 자산 — 상세 패널이 이 자산으로 옮겨 간다. */
  assetId: string;
  /** 이 매체의 포트만 고를 수 있다(케이블 종류가 정한다). `null` 이면 가리지 않는다. */
  medium: string | null;
  /** 첫 끝점 — 자기 자신에게 잇는 것을 막고, 안내에 출발점으로 적는다. */
  firstEndpoint: { portId: string; label: string } | null;
  /** 못 잇는 까닭 — 고른 뒤 검증에 걸리면 채워진다. */
  error: string | null;
  onSelect: (port: V2Port) => void;
  onCancel: () => void;
  /** 대국(다른 변전소)에서 찾기 — 첫 끝점이 정해진 뒤에만 있다. */
  onSearchRemote?: () => void;
}
